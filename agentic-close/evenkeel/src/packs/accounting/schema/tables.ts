import { newId, nowIso } from '../../../framework/store/defaults';
import { t, table } from '../../../framework/store/schema';
import { ENTRY_TYPES, ISSUE_CATEGORIES, MATCH_TYPES, PROPOSAL_KINDS, RECONCILING_ITEM_TYPES, TASK_STATUSES } from '../ontology/shapes';

/**
 * Evenkeel relational model (Postgres semantics). Mirrors db/migrations/*.sql exactly;
 * tests/integration/schema-contract.test.ts compares this registry with information_schema.
 */
const id = () => t.uuid().default(() => newId());
const createdAt = () => t.timestamptz().default(() => nowIso());
const tenant = () => t.uuid().references('tenant');
const user = () => t.uuid().references('app_user').nullable();
const money = () => t.bigint();

export const ACCOUNT_CLASSES = ['asset', 'liability', 'equity', 'revenue', 'expense'] as const;
export const SUBLEDGERS = ['ap', 'ar', 'bank', 'card', 'fixed_asset', 'prepaid', 'payroll'] as const;
export const PERIOD_STATUSES = ['open', 'soft_close', 'hard_close'] as const;
export const JE_STATUSES = ['draft', 'pending_approval', 'posted', 'rejected'] as const;
export const JE_SOURCES = ['manual', 'agent', 'import', 'system', 'subledger'] as const;
export const AUTONOMY = ['L0', 'L1', 'L2', 'L3'] as const;
export const PROPOSAL_STATUSES = ['pending', 'approved', 'rejected', 'auto_applied', 'applied', 'superseded', 'failed', 'suggested'] as const;
export const RUN_STATUSES = ['queued', 'running', 'awaiting_approval', 'completed', 'failed', 'cancelled', 'budget_exceeded'] as const;
export const STEP_PHASES = ['plan', 'act', 'observe', 'verify', 'propose', 'gate', 'post', 'audit', 'finish', 'error'] as const;
export const CONNECTOR_KINDS = ['bank_bai2', 'bank_camt053', 'bank_ofx', 'bank_csv', 'card_csv', 'ap_bills_csv', 'ar_invoices_csv', 'payroll_csv', 'gl_journal_csv', 'erp_gl_json'] as const;
export const TASK_CATEGORIES = ['cash', 'ap', 'ar', 'accruals', 'prepaids', 'fixed_assets', 'payroll', 'intercompany', 'fx', 'review', 'reporting', 'controls'] as const;
export const REC_STATUSES = ['not_started', 'in_progress', 'prepared', 'reviewed'] as const;
export const REC_TYPES = ['bank', 'subledger', 'intercompany', 'balance_substantiation', 'card'] as const;

