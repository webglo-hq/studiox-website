/*
 * `npm run docs:erd`: generate docs/erd.md — Mermaid entity-relationship diagrams of the
 * PostgreSQL schema, one per area, straight from the table registry (the same registry the
 * integration suite checks against the live catalog, so the diagram cannot drift).
 */
import { writeFileSync } from 'node:fs';
import type { Schema, TableSpec } from '../src/framework/store/schema';
import { schema } from '../src/packs/accounting/store';
import { fromRoot } from '../src/server/paths';

const AREAS: { title: string; note: string; tables: string[] }[] = [
  { title: 'Tenancy, identity and access', note: 'Users, roles and permissions (RBAC), segregation-of-duties rules, sessions and API tokens. Every business row carries tenant_id.', tables: ['tenant', 'app_user', 'role', 'role_permission', 'user_role', 'sod_rule', 'session', 'api_token', 'login_attempt'] },
  { title: 'General ledger', note: 'Multi-entity, multi-currency double entry. Posting is enforced by triggers: balanced, at least two lines, postable accounts, open period, maker-checker; posted entries are immutable and corrected only by mirror reversals.', tables: ['entity', 'currency', 'fx_rate', 'fs_line_item', 'account', 'dimension_type', 'dimension_value', 'fiscal_period', 'holiday', 'journal_entry', 'journal_line', 'je_sequence'] },
  { title: 'Subledgers and source data', note: 'Procure-to-pay, order-to-cash, cash, cards, fixed assets, prepaids, payroll and budgets, with import provenance (connector → import batch → source document).', tables: ['vendor', 'purchase_order', 'bill', 'vendor_payment', 'customer', 'invoice', 'customer_receipt', 'bank_account', 'bank_statement', 'bank_transaction', 'card_transaction', 'fixed_asset', 'depreciation_line', 'prepaid_schedule', 'prepaid_line', 'payroll_run', 'payroll_line', 'budget', 'budget_line', 'connector', 'import_batch', 'source_document'] },
  { title: 'Close management', note: 'The close calendar and its task graph (acyclic by trigger), reconciliations with matches and reconciling items, flux analysis, evidence, sign-offs and the close package.', tables: ['close_cycle', 'close_task', 'close_task_dependency', 'signoff', 'close_package', 'reconciliation', 'rec_match', 'rec_match_item', 'reconciling_item', 'evidence', 'flux_analysis', 'flux_line', 'flux_explanation', 'issue'] },
  { title: 'Agents, skills and audit', note: 'Durable agent runs (steps, tool calls, proposals, human approvals), versioned skills and policies, evaluation results, and the hash-chained, append-only audit log.', tables: ['skill', 'skill_version', 'skill_policy', 'eval_run', 'agent_run', 'agent_step', 'tool_call', 'proposal', 'approval', 'audit_log', 'audit_chain_head'] },
];

const all = schema as Schema;
const placed = new Set(AREAS.flatMap((a) => a.tables));
const missing = Object.keys(all).filter((t) => !placed.has(t));
if (missing.length) throw new Error(`Tables not assigned to an area: ${missing.join(', ')}`);

const TYPE: Record<string, string> = { uuid: 'uuid', text: 'text', int: 'int', bigint: 'bigint', numeric: 'numeric', bool: 'bool', date: 'date', timestamptz: 'timestamptz', json: 'jsonb' };

function entity(spec: TableSpec, full: boolean): string {
  const pk = spec.primaryKey ?? 'id';
  const uniques = new Set((spec.unique ?? []).filter((u) => u.length === 1).map((u) => u[0]));
  const rows = Object.entries(spec.columns)
    .filter(([name, col]) => full || name === pk || col.spec.references)
    .map(([name, col]) => {
      const keys = [name === pk ? 'PK' : null, col.spec.references ? 'FK' : null, uniques.has(name) && name !== pk ? 'UK' : null].filter(Boolean).join(', ');
      return `    ${TYPE[col.spec.kind]} ${name}${keys ? ` ${keys}` : ''}`;
    });
  return `  ${spec.name} {\n${rows.join('\n')}\n  }`;
}

const out: string[] = [
  '# Evenkeel data model (ERD)',
  '',
  '> Generated by `npm run docs:erd` from the table registry in `src/packs/accounting/schema/tables.ts`. The integration suite (`tests/integration/postgres.test.ts`) checks the same registry against the PostgreSQL 16 catalog: tables, columns, types, nullability, enumerations, foreign keys, unique keys, named checks and triggers.',
  '',
  `${Object.keys(all).length} tables in five areas. Money is stored as integer minor units (bigint cents). Enumerations are text with named CHECK constraints. Ledger, period, proposal and audit rules are enforced by triggers in \`db/migrations/0002_invariants.sql\` (see the axiom codes such as EK-DE-01 in the error messages).`,
  '',
  'Tables from another area appear with their keys only.',
  '',
];
for (const area of AREAS) {
  const inArea = new Set(area.tables);
  const external = new Set<string>();
  const edges: string[] = [];
  for (const t of area.tables) {
    const spec: TableSpec = all[t]!;
    for (const [name, col] of Object.entries(spec.columns)) {
      const ref = col.spec.references;
      if (!ref || (ref.table === 'tenant' && area.title !== 'Tenancy, identity and access')) continue;
      if (!inArea.has(ref.table)) external.add(ref.table);
      const card = col.spec.nullable ? '|o--o{' : '||--o{';
      edges.push(`  ${ref.table} ${card} ${t} : "${name}"`);
    }
  }
  out.push(`## ${area.title}`, '', area.note, '', '```mermaid', 'erDiagram');
  for (const t of area.tables) out.push(entity(all[t]!, true));
  for (const t of [...external].sort()) out.push(entity(all[t]!, false));
  out.push(...[...new Set(edges)]);
  out.push('```', '');
}
out.push('Every tenant-scoped table also references `tenant(id)`; those edges are drawn only in the first diagram to keep the others readable.', '');
const file = fromRoot('docs', 'erd.md');
writeFileSync(file, out.join('\n'));
console.log(`Wrote ${file} (${Object.keys(all).length} tables)`);
