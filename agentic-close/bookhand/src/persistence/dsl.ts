/**
 * Schema DSL. One declarative description of every table drives:
 *   1. TypeScript row/insert types (inferred),
 *   2. the in-memory adapter's constraint engine (PK, unique, FK, enum, check),
 *   3. the generated Postgres DDL (db/migrations/0001_schema.sql, and later generated migrations), and
 *   4. the parity test that proves both adapters enforce the same rules.
 * Business invariants that need procedural logic (balanced posting, immutability, period locks,
 * audit hash chain) live in triggers (SQL) and guards (memory) - see invariants.ts.
 */

export type SqlType =
  | 'uuid'
  | 'text'
  | 'integer'
  | 'bigint'
  | 'numeric'
  | 'boolean'
  | 'date'
  | 'timestamptz'
  | 'jsonb'
  | 'bytea';

export interface ReferenceSpec {
  table: string;
  column: string;
  onDelete: 'restrict' | 'cascade' | 'set null';
}

export interface ColumnSpec {
  sqlType: SqlType;
  nullable: boolean;
  hasDefault: boolean;
  /** Literal default (also rendered into DDL). */
  defaultLiteral?: string | number | boolean | null | object;
  /** Generated default: 'now' timestamp or 'uuid'. Rendered as now() / gen_random_uuid(). */
  defaultGen?: 'now' | 'uuid' | 'today';
  primaryKey?: boolean;
  unique?: boolean;
  references?: ReferenceSpec;
  enumValues?: readonly string[];
  /** Column-level CHECK (SQL expression using the column name) and its JS twin. */
  checkSql?: string;
  checkFn?: (value: unknown) => boolean;
  numeric?: { precision: number; scale: number };
  description?: string;
}

export class Col<T, N extends boolean = false, D extends boolean = false> {
  declare readonly __type: T;
  declare readonly __nullable: N;
  declare readonly __default: D;
  readonly spec: ColumnSpec;

  constructor(spec: ColumnSpec) {
    this.spec = spec;
  }

  nullable(): Col<T, true, D> {
    return new Col<T, true, D>({ ...this.spec, nullable: true });
  }

  /** Constant default. */
  default(value: T & (string | number | boolean | object | null)): Col<T, N, true> {
    return new Col<T, N, true>({ ...this.spec, hasDefault: true, defaultLiteral: value });
  }

  defaultNow(): Col<T, N, true> {
    return new Col<T, N, true>({ ...this.spec, hasDefault: true, defaultGen: 'now' });
  }

  defaultRandom(): Col<T, N, true> {
    return new Col<T, N, true>({ ...this.spec, hasDefault: true, defaultGen: 'uuid' });
  }

  pk(): Col<T, N, true> {
    return new Col<T, N, true>({ ...this.spec, primaryKey: true, hasDefault: true, defaultGen: this.spec.defaultGen ?? 'uuid' });
  }

  unique(): Col<T, N, D> {
    return new Col<T, N, D>({ ...this.spec, unique: true });
  }

  references(table: string, onDelete: ReferenceSpec['onDelete'] = 'restrict', column = 'id'): Col<T, N, D> {
    return new Col<T, N, D>({ ...this.spec, references: { table, column, onDelete } });
  }

  check(sql: string, fn: (value: T) => boolean): Col<T, N, D> {
    return new Col<T, N, D>({ ...this.spec, checkSql: sql, checkFn: fn as (v: unknown) => boolean });
  }

  describe(text: string): Col<T, N, D> {
    return new Col<T, N, D>({ ...this.spec, description: text });
  }
}

// Column constructors -------------------------------------------------------------------------

const base = (sqlType: SqlType, extra: Partial<ColumnSpec> = {}): ColumnSpec => ({
  sqlType,
  nullable: false,
  hasDefault: false,
  ...extra,
});

export const c = {
  /** Primary key UUID generated by the app (random) or the seed (deterministic). */
  id: () => new Col<string>(base('uuid')).pk(),
  uuid: () => new Col<string>(base('uuid')),
  text: () => new Col<string>(base('text')),
  enum: <const V extends string>(values: readonly V[]) => new Col<V>(base('text', { enumValues: values })),
  int: () => new Col<number>(base('integer')),
  /** Money in integer minor units (cents/pence). */
  money: () => new Col<number>(base('bigint')),
  bigint: () => new Col<number>(base('bigint')),
  numeric: (precision = 18, scale = 6) => new Col<number>(base('numeric', { numeric: { precision, scale } })),
  bool: () => new Col<boolean>(base('boolean')),
  date: () => new Col<string>(base('date')),
  timestamp: () => new Col<string>(base('timestamptz')),
  json: <T>() => new Col<T>(base('jsonb')),
  bytes: () => new Col<Uint8Array>(base('bytea')),
  currency: () => new Col<string>(base('text', { checkSql: "~ '^[A-Z]{3}$'", checkFn: (v) => typeof v === 'string' && /^[A-Z]{3}$/.test(v) })),
};

// Tables -----------------------------------------------------------------------------------------

export type AnyCol = Col<unknown, boolean, boolean>;
export type Columns = Record<string, Col<any, any, any>>; // eslint-disable-line @typescript-eslint/no-explicit-any

export interface TableCheck {
  name: string;
  sql: string;
  /** JS twin of the SQL check, evaluated by the memory adapter on the full row. */
  test: (row: Record<string, unknown>) => boolean;
  message: string;
}

export interface UniqueSpec {
  columns: string[];
  /** Postgres 15+ UNIQUE NULLS NOT DISTINCT: NULLs compare equal. */
  nullsNotDistinct?: boolean;
}

export interface TableOptions {
  description: string;
  /** Ontology class this table materializes (ties the data model to the semantic layer). */
  ontologyClass?: string;
  uniques?: Array<string[] | UniqueSpec>;
  indexes?: string[][];
  checks?: TableCheck[];
  /** Append-only table: UPDATE and DELETE rejected (audit log, approvals, policy versions). */
  appendOnly?: boolean;
  /** Logical area for docs/ERD grouping. */
  area: string;
  /**
   * Version of the generated migration that creates the table (default "0001"). Applied migrations never
   * change, so a table added later is generated into its own migration file (see ddl.ts GENERATED_MIGRATIONS).
   */
  migration?: string;
}

export interface TableSpec<Cols extends Columns = Columns> extends TableOptions {
  name: string;
  columns: Cols;
  columnNames: string[];
}

export function table<const Name extends string, Cols extends Columns>(
  name: Name,
  columns: Cols,
  options: TableOptions,
): TableSpec<Cols> & { name: Name } {
  return {
    name,
    columns,
    columnNames: Object.keys(columns),
    ...options,
  };
}

export function normalizeUnique(u: string[] | UniqueSpec): UniqueSpec {
  return Array.isArray(u) ? { columns: u } : u;
}

/** UNIQUE NULLS NOT DISTINCT helper. */
export function nnd(...columns: string[]): UniqueSpec {
  return { columns, nullsNotDistinct: true };
}

/** Helper for table-level checks with a JS twin. */
export function check(
  name: string,
  sql: string,
  test: (row: Record<string, unknown>) => boolean,
  message: string,
): TableCheck {
  return { name, sql, test, message };
}

// Type inference -------------------------------------------------------------------------------

type ColValue<C> = C extends Col<infer T, infer N, infer _D> ? (N extends true ? T | null : T) : never;

export type RowOf<Cols extends Columns> = { [K in keyof Cols]: ColValue<Cols[K]> };

type RequiredKeys<Cols extends Columns> = {
  [K in keyof Cols]: Cols[K] extends Col<infer _T, infer N, infer D>
    ? N extends true
      ? never
      : D extends true
        ? never
        : K
    : never;
}[keyof Cols];

type OptionalKeys<Cols extends Columns> = Exclude<keyof Cols, RequiredKeys<Cols>>;

export type InsertOf<Cols extends Columns> = { [K in RequiredKeys<Cols>]: ColValue<Cols[K]> } & {
  [K in OptionalKeys<Cols>]?: ColValue<Cols[K]>;
};
