/**
 * Bundles every skill package (SKILL.md + evals.json) under src/packs/accounting/skills into a generated
 * TypeScript module, so the same skills load in Node, in tests and in the zero-install browser demo.
 * Usage: npm run skills:bundle   (CI checks the bundle is current: tests/unit/skills-bundle.test.ts)
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skillsDir = join(root, 'src/packs/accounting/skills');
const outFile = join(skillsDir, 'bundle.generated.ts');

export function renderBundle(): string {
  const entries = readdirSync(skillsDir)
    .filter((d) => statSync(join(skillsDir, d)).isDirectory() && existsSync(join(skillsDir, d, 'SKILL.md')))
    .sort()
    .map((d) => {
      const skillMd = readFileSync(join(skillsDir, d, 'SKILL.md'), 'utf8');
      const evalsPath = join(skillsDir, d, 'evals.json');
      const evals = existsSync(evalsPath) ? readFileSync(evalsPath, 'utf8') : null;
      return `  { key: ${JSON.stringify(d)}, skillMd: ${JSON.stringify(skillMd)}, evals: ${JSON.stringify(evals)} },`;
    });
  return `// Generated by scripts/bundle-skills.ts from src/packs/accounting/skills/*/SKILL.md - do not edit by hand.\n\nexport interface BundledSkill {\n  key: string;\n  skillMd: string;\n  evals: string | null;\n}\n\nexport const SKILL_FILES: ReadonlyArray<BundledSkill> = [\n${entries.join('\n')}\n];\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderBundle();
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error('skills bundle is stale: run npm run skills:bundle');
      process.exit(1);
    }
    console.log('skills bundle is current');
  } else {
    writeFileSync(outFile, text);
    console.log(`wrote ${outFile.replace(root + '/', '')}`);
  }
}
