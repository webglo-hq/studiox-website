export function payDatesUS(periodKey: string): string[] {
  // biweekly Fridays anchored on 2025-09-05
  const out: string[] = [];
  let d = '2025-09-05';
  while (d <= periodEnd(periodKey)) {
    if (d >= periodStart(periodKey)) out.push(d);
    d = addDays(d, 14);
  }
  return out;
}

function businessDayOnOrBefore(iso: string, cal: 'US' | 'UK' = 'US'): string {
  let d = iso;
  while (!isBusinessDay(d, cal)) d = addDays(d, -1);
  return d;
}

function businessDayOnOrAfter(iso: string, cal: 'US' | 'UK' = 'US'): string {
  let d = iso;
  while (!isBusinessDay(d, cal)) d = addDays(d, 1);
  return d;
}

/** Bank clearing date: book date + lag on a business day, kept inside the book month (history months reconcile cleanly). */
export function clearDate(book: string, lagDays: number, cal: 'US' | 'UK'): string {
  const d = businessDayOnOrAfter(addDays(book, lagDays), cal);
  return periodKeyOf(d) === periodKeyOf(book) ? d : book;
}

export function generateFx(st: HistoryState, from: string, to: string) {
  const { b } = st;
  let rate = 1.3195;
  let d = from;
  const rng = b.rng.fork('fx');
  while (d <= to) {
    if (!isWeekend(d)) {
      const shock = rng.normal(0, 0.0032);
      rate = rate + (1.335 - rate) * 0.02 + rate * shock;
      rate = Math.round(rate * 10000) / 10000;
    }
    st.spot.set(d, rate);
    d = addDays(d, 1);
  }
  // pin the scenario's September path so the reval and IC story read cleanly
  st.spot.set('2026-08-31', 1.3287);
  st.spot.set('2026-09-30', 1.3412);
  for (const pk of periodRange(periodKeyOf(from), periodKeyOf(to))) {
    const days = [...st.spot.entries()].filter(([k]) => periodKeyOf(k) === pk && !isWeekend(k)).map(([, v]) => v);
    if (!days.length) continue;
    const avg = Math.round((days.reduce((s, x) => s + x, 0) / days.length) * 1e6) / 1e6;
    st.average.set(pk, avg);
    const end = periodEnd(pk);
    if (end <= to) st.closing.set(pk, st.spot.get(end)!);
  }
  for (const [date, r] of st.spot) if (date <= to) b.add('fx_rates', { rate_date: date, from_currency: 'GBP', to_currency: 'USD', rate_type: 'spot', rate: r, period_key: null, source: 'Fictional rate feed (seeded)' });
  for (const [pk, r] of st.average) b.add('fx_rates', { rate_date: periodEnd(pk) <= to ? periodEnd(pk) : to, from_currency: 'GBP', to_currency: 'USD', rate_type: 'average', rate: r, period_key: pk, source: 'Fictional rate feed (seeded)' });
  for (const [pk, r] of st.closing) b.add('fx_rates', { rate_date: periodEnd(pk), from_currency: 'GBP', to_currency: 'USD', rate_type: 'closing', rate: r, period_key: pk, source: 'Fictional rate feed (seeded)' });
}

export function spotOn(st: HistoryState, date: string): number {
  let d = date;
  for (let i = 0; i < 10; i++) {
    const r = st.spot.get(d);
    if (r) return r;
    d = addDays(d, -1);
  }
  throw new Error(`no spot rate near ${date}`);
}

// ---------------------------------------------------------------------------- customers
export function buildCustomers(st: HistoryState) {
  const rng = st.b.rng.fork('customers');
  const mk = (names: string[], entity: 'BWL-US' | 'BWL-UK', minArr: number, maxArr: number) =>
    names.map((name, i) => {
      const code = `${entity === 'BWL-US' ? 'C' : 'CUK'}-${String(i + 1).padStart(3, '0')}`;
      const row = st.b.add('customers', { entity_id: st.b.ent(entity), code, name, segment: rng.pick(['Utilities', 'Agriculture', 'Ports & logistics', 'Public sector', 'Energy']), payment_terms_days: rng.pick([30, 30, 45, 60]), is_intercompany: false, counterparty_entity_id: null, status: 'active' });
      // multiples of 12 minor units so monthly ratable release is exact (no rounding drift)
      const arr = Math.round(Math.exp(rng.float(Math.log(minArr), Math.log(maxArr))) / 1200) * 1200;
      const startKey = i >= names.length - 4 ? shiftPeriod(SCENARIO.historyStart, rng.int(2, 10)) : '2023-01';
      const anniversary = startKey === '2023-01' ? rng.int(1, 12) : Number(startKey.slice(5));
      const sim: CustomerSim = { id: row.id, name, entity, arr, billing: rng.chance(0.6) ? 'annual' : 'monthly', anniversary, terms: row.payment_terms_days as number, lateness: rng.pick([0, 0, 2, 5, 9, 14]), startKey };
      return sim;
    });
  st.customers = [...mk(CUSTOMERS_US, 'BWL-US', 6_000_000, 120_000_000), ...mk(CUSTOMERS_UK, 'BWL-UK', 2_400_000, 36_000_000)];
}

