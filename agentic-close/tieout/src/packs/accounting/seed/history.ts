function nextInvoiceNo(st: HistoryState, entity: string, pk: string): string {
  const k = `${entity}:${pk}`;
  st.invoiceNo[k] = (st.invoiceNo[k] ?? 0) + 1;
  return `INV-${entity === 'BWL-US' ? 'US' : 'UK'}-${pk.replace('-', '')}-${String(st.invoiceNo[k]).padStart(3, '0')}`;
}

function nextPayment(st: HistoryState, entity: string): string {
  st.paymentNo++;
  return `PAY-${entity === 'BWL-US' ? 'US' : 'UK'}-${String(st.paymentNo).padStart(5, '0')}`;
}

// ---------------------------------------------------------------------------- AR
export function issueInvoice(
  st: HistoryState,
  c: CustomerSim,
  date: string,
  lines: { description: string; amount: number; revenueType: 'subscription' | 'hardware' | 'services'; account: string; start?: string; end?: string; productClass: string }[],
  opts: { opening?: boolean; openingJeId?: string } = {},
) {
  const { b } = st;
  const pk = periodKeyOf(date);
  const number = nextInvoiceNo(st, c.entity, pk);
  const total = lines.reduce((s, l) => s + l.amount, 0);
  let jeId: string | null = opts.openingJeId ?? null;
  if (!opts.opening) {
    jeId = b.je({
      entity: c.entity, date, type: 'standard', memo: `Invoice ${number} – ${c.name}`, source: 'subledger', sourceRef: number, ...sys(st),
      lines: [
        { account: '1100', debit: total, memo: c.name },
        ...lines.map((l) => ({ account: l.account, credit: l.amount, product_class: l.productClass, memo: l.description })),
      ],
    });
  }
  const due = addDays(date, c.terms);
  const inv = b.add('invoices', { entity_id: b.ent(c.entity), customer_id: c.id, invoice_number: number, invoice_date: date, due_date: due, currency: c.entity === 'BWL-US' ? 'USD' : 'GBP', total_minor: total, status: 'posted', journal_entry_id: jeId, description: lines[0]!.description });
  st.invoiceById.set(inv.id, inv as Record<string, unknown>);
  lines.forEach((l, i) => b.add('invoice_lines', { invoice_id: inv.id, line_no: i + 1, description: l.description, amount_minor: l.amount, revenue_type: l.revenueType, account_id: b.acct(l.account), service_start: l.start ?? null, service_end: l.end ?? null, product_class: l.productClass }));
  const payDate = businessDayOnOrAfter(addDays(due, c.lateness + b.rng.int(-6, 4)), c.entity === 'BWL-US' ? 'US' : 'UK');
  st.openInvoices.push({ invoiceId: inv.id, customerId: c.id, customerName: c.name, amount: total, due, entity: c.entity, number, payDate: payDate < date ? addDays(date, 3) : payDate });
  return inv;
}

/** Cash receipts due within [from, to]; batches same-day US receipts into lockbox deposits. */
export function collectReceipts(st: HistoryState, from: string, to: string, opts: { skip?: (inv: HistoryState['openInvoices'][number]) => boolean } = {}) {
  const { b } = st;
  const due = st.openInvoices.filter((i) => i.payDate >= from && i.payDate <= to && !opts.skip?.(i));
  const byDate = new Map<string, typeof due>();
  for (const inv of due) {
    const k = `${inv.entity}:${inv.payDate}`;
    byDate.set(k, [...(byDate.get(k) ?? []), inv]);
  }
  for (const [k, invs] of [...byDate.entries()].sort()) {
    const [entity, date] = k.split(':') as [string, string];
    const ba = st.bankAccount[entity]!;
    const lockbox = entity === 'BWL-US' && invs.length >= 2 && b.rng.chance(0.55);
    let lockboxTotal = 0;
    for (const inv of invs) {
      const method = inv.amount > 5_000_000 ? 'wire' : 'ach';
      const rcp = b.add('receipts', { entity_id: b.ent(entity), customer_id: inv.customerId, bank_account_id: ba.id, receipt_date: date, amount_minor: inv.amount, currency: ba.currency, method, reference: inv.number, status: 'cleared', journal_entry_id: null });
      const jeId = b.je({ entity, date, type: 'standard', memo: `Receipt ${inv.number} – ${inv.customerName}`, source: 'subledger', sourceRef: inv.number, ...sys(st), lines: [{ account: ba.gl, debit: inv.amount, memo: inv.customerName }, { account: '1100', credit: inv.amount, memo: inv.number }] });
      (rcp as Record<string, unknown>).journal_entry_id = jeId;
      b.add('receipt_applications', { receipt_id: rcp.id, invoice_id: inv.invoiceId, amount_minor: inv.amount });
      st.invoiceById.get(inv.invoiceId)!.status = 'paid';
      if (lockbox) lockboxTotal += inv.amount;
      else bank(st, entity, clearDate(date, b.rng.int(0, 1), entity === 'BWL-US' ? 'US' : 'UK'), inv.amount, method === 'wire' ? `WIRE IN ${inv.customerName.toUpperCase()} REF ${inv.number}` : `ACH CREDIT ${inv.customerName.toUpperCase().slice(0, 22)} ${inv.number}`, inv.customerName, inv.number, method === 'wire' ? '195' : '165');
    }
    if (lockbox) bank(st, entity, clearDate(date, 1, 'US'), lockboxTotal, `LOCKBOX DEPOSIT ${invs.length} ITEMS`, null, `LBX-${date.replace(/-/g, '')}`, '115');
    st.openInvoices = st.openInvoices.filter((i) => !invs.includes(i));
  }
}

