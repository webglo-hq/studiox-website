export function postBill(
  st: HistoryState,
  v: VendorDef,
  billDate: string,
  amount: number,
  opts: { glDate?: string; description?: string; account?: string; dept?: string | null; project?: string | null; servicePeriod?: [string, string]; poId?: string; billNumber?: string; opening?: boolean; openingJeId?: string; status?: 'posted' | 'received'; receivedDate?: string; lines?: { description: string; amount: number; account: string; dept: string | null; project?: string | null }[]; payOn?: string | null } = {},
) {
  const { b } = st;
  const entity = v.entity;
  const glDate = opts.glDate ?? billDate;
  const number = opts.billNumber ?? `${v.code.replace('V-', '').slice(0, 4)}-${billDate.replace(/-/g, '').slice(2)}${b.rng.int(10, 99)}`;
  const lines = opts.lines ?? [{ description: opts.description ?? `${v.category} – ${periodKeyOf(glDate)}`, amount, account: opts.account ?? v.account, dept: opts.dept !== undefined ? opts.dept : v.dept, project: opts.project ?? null }];
  const total = lines.reduce((s, l) => s + l.amount, 0);
  let jeId: string | null = opts.openingJeId ?? null;
  const status = opts.status ?? 'posted';
  if (status === 'posted' && !opts.opening) {
    jeId = b.je({
      entity, date: glDate, type: 'standard', memo: `Bill ${number} – ${v.name}`, source: 'subledger', sourceRef: number, ...sys(st),
      lines: [...lines.map((l) => ({ account: l.account, debit: l.amount, department: requiresDept(l.account) ? (l.dept ?? 'GA') : null, project: l.project ?? null, memo: l.description })), { account: '2000', credit: total, memo: v.name }],
    });
  }
  const due = addDays(billDate, v.terms);
  const bill = b.add('bills', {
    entity_id: b.ent(entity), vendor_id: st.vendorIds.get(v.code)!, bill_number: number, bill_date: billDate, due_date: due, received_date: opts.receivedDate ?? billDate,
    service_period_start: opts.servicePeriod?.[0] ?? null, service_period_end: opts.servicePeriod?.[1] ?? null, currency: entity === 'BWL-US' ? 'USD' : 'GBP', total_minor: total,
    status: status === 'posted' ? 'posted' : 'received', purchase_order_id: opts.poId ?? null, journal_entry_id: jeId, source_document_id: null, import_batch_id: null, external_id: null, description: lines[0]!.description,
  });
  st.billById.set(bill.id, bill as Record<string, unknown>);
  lines.forEach((l, i) => b.add('bill_lines', { bill_id: bill.id, line_no: i + 1, description: l.description, amount_minor: l.amount, account_id: b.acct(l.account), department: requiresDept(l.account) ? (l.dept ?? 'GA') : null, location: null, product_class: null, project: l.project ?? null, coding_source: 'human', coding_confidence: null }));
  if (status === 'posted' && opts.payOn !== null) st.openBills.push({ billId: bill.id, vendor: v, amount: total, due: opts.payOn ?? due, entity, number });
  return bill;
}

const DEPT_ACCOUNTS = new Set(['6000', '6010', '6020', '6100', '6150', '6300', '6310', '6400', '6410', '6500', '6510', '6600', '6650', '6700', '6800', '6900', '6950']);
export const requiresDept = (code: string) => DEPT_ACCOUNTS.has(code);

/** Pay bills due within [from, to]. */
export function payBills(st: HistoryState, from: string, to: string, opts: { skip?: (b: HistoryState['openBills'][number]) => boolean } = {}) {
  const { b } = st;
  const due = st.openBills.filter((x) => x.due <= to && !opts.skip?.(x)).sort((x, y) => x.due.localeCompare(y.due));
  for (const bill of due) {
    const cal = bill.entity === 'BWL-US' ? 'US' : 'UK';
    let date = businessDayOnOrAfter(bill.due < from ? from : bill.due, cal);
    if (date > to) date = businessDayOnOrBefore(to, cal);
    const ba = st.bankAccount[bill.entity]!;
    const method = bill.vendor.method ?? 'ach';
    const number = nextPayment(st, bill.entity);
    const checkNo = method === 'check' ? String(++st.checkNo) : null;
    const pay = b.add('payments', { entity_id: b.ent(bill.entity), vendor_id: st.vendorIds.get(bill.vendor.code)!, bank_account_id: ba.id, payment_number: number, payment_date: date, method, check_number: checkNo, amount_minor: bill.amount, currency: ba.currency, reference: bill.number, status: 'cleared', journal_entry_id: null, approved_by: b.user('casey') });
    const jeId = b.je({ entity: bill.entity, date, type: 'standard', memo: `Payment ${number} – ${bill.vendor.name}`, source: 'subledger', sourceRef: number, ...sys(st), lines: [{ account: '2000', debit: bill.amount, memo: bill.number }, { account: ba.gl, credit: bill.amount, memo: bill.vendor.name }] });
    (pay as Record<string, unknown>).journal_entry_id = jeId;
    b.add('payment_applications', { payment_id: pay.id, bill_id: bill.billId, amount_minor: bill.amount });
    st.billById.get(bill.billId)!.status = 'paid';
    const lag = method === 'check' ? b.rng.int(2, 6) : method === 'wire' ? 0 : b.rng.int(0, 1);
    const desc = method === 'check' ? `CHECK ${checkNo}` : method === 'wire' ? `WIRE OUT ${bill.vendor.name.toUpperCase()} ${bill.number}` : `ACH DEBIT ${bill.vendor.name.toUpperCase().slice(0, 22)} ${number}`;
    bank(st, bill.entity, clearDate(date, lag, cal), -bill.amount, desc, bill.vendor.name, method === 'check' ? checkNo : number, method === 'check' ? '475' : method === 'wire' ? '495' : '455');
  }
  st.openBills = st.openBills.filter((x) => !due.includes(x));
}

// ---------------------------------------------------------------------------- payroll
export function runPayroll(st: HistoryState, entity: 'BWL-US' | 'BWL-UK', payDate: string, periodStartDate: string, periodEndDate: string, monthlyFraction: number) {
  const { b } = st;
  const depts = entity === 'BWL-US' ? PEOPLE_DEPTS_US : PEOPLE_DEPTS_UK;
  const salary = entity === 'BWL-US' ? SALARY_US : SALARY_UK;
  const growth = 1 + 0.004 * monthsSince(periodKeyOf(payDate));
  const byDept: Record<string, number> = {};
  for (const [d, n] of Object.entries(depts)) byDept[d] = Math.round((n * salary * monthlyFraction * growth * (1 + b.rng.normal(0, 0.01))) / 100) * 100;
  const gross = Object.values(byDept).reduce((s, x) => s + x, 0);
  const taxes = Math.round(gross * (entity === 'BWL-US' ? 0.072 : 0.138));
  const benefits = Math.round(gross * (entity === 'BWL-US' ? 0.09 : 0.05));
  const withholdings = Math.round(gross * (entity === 'BWL-US' ? 0.28 : 0.31));
  const net = gross - withholdings;
  const ba = st.bankAccount[entity]!;
  const lines = Object.entries(byDept).flatMap(([d, g]) => [
    { account: '6000', debit: g, department: d },
    { account: '6010', debit: Math.round((g * taxes) / gross), department: d },
    { account: '6020', debit: Math.round((g * benefits) / gross), department: d },
  ]);
  const drTotal = lines.reduce((s, l) => s + l.debit, 0);
  const liability = drTotal - net;
  const ext = `PR-${entity === 'BWL-US' ? 'US' : 'UK'}-${payDate.replace(/-/g, '')}`;
  const jeId = b.je({ entity, date: payDate, type: 'standard', memo: `Payroll ${payDate} (${periodStartDate} to ${periodEndDate})`, source: 'subledger', sourceRef: ext, ...sys(st), lines: [...lines, { account: ba.gl, credit: net, memo: 'Net pay' }, { account: '2500', credit: liability, memo: 'Taxes, withholdings and benefits payable' }] });
  b.add('payroll_runs', { entity_id: b.ent(entity), provider: entity === 'BWL-US' ? 'Pebble Payroll Services' : 'Pebble Payroll UK', pay_date: payDate, period_start: periodStartDate, period_end: periodEndDate, currency: ba.currency, gross_minor: gross, employer_taxes_minor: taxes, benefits_minor: benefits, withholdings_minor: withholdings, net_pay_minor: net, by_department: byDept, journal_entry_id: jeId, import_batch_id: null, source_document_id: null, external_id: ext });
  const cal = entity === 'BWL-US' ? 'US' : 'UK';
  // net pay sometimes settles as two debits (many-to-one)
  if (entity === 'BWL-US' && b.rng.chance(0.5)) {
    const first = Math.round(net * 0.62);
    bank(st, entity, payDate, -first, 'PEBBLE PAYROLL NET PAY 1/2', 'Pebble Payroll Services', ext, '455');
    bank(st, entity, payDate, -(net - first), 'PEBBLE PAYROLL NET PAY 2/2', 'Pebble Payroll Services', ext, '455');
  } else bank(st, entity, payDate, -net, 'PEBBLE PAYROLL NET PAY', 'Pebble Payroll Services', ext, '455');
  const remitDate = businessDayOnOrAfter(addDays(payDate, 2), cal);
  const remit = periodKeyOf(remitDate) === periodKeyOf(payDate) ? remitDate : businessDayOnOrBefore(periodEnd(periodKeyOf(payDate)), cal);
  b.je({ entity, date: remit, type: 'standard', memo: `Payroll tax and benefit remittance ${payDate}`, source: 'subledger', sourceRef: `${ext}-TAX`, ...sys(st), lines: [{ account: '2500', debit: liability }, { account: ba.gl, credit: liability }] });
  bank(st, entity, remit, -liability, 'PEBBLE TAX & BENEFITS REMIT', 'Pebble Payroll Services', `${ext}-TAX`, '455');
  return { gross, byDept, dailyRate: drTotal / 10 };
}

export function monthsSince(pk: string): number {
  const [y, m] = pk.split('-').map(Number) as [number, number];
  return (y - 2025) * 12 + (m - 9);
}

export function payrollAccrual(_st: HistoryState, _entity: 'BWL-US', pk: string): { amount: number; byDept: Record<string, number>; days: number; from: string } | null {
  // unpaid workdays between the last pay period end (pay date - 6) and month end
  const pays = payDatesUS(pk);
  const lastPay = pays[pays.length - 1];
  if (!lastPay) return null;
  const covered = addDays(lastPay, -6);
  let d = addDays(covered, 1);
  let days = 0;
  const end = periodEnd(pk);
  while (d <= end) {
    if (isBusinessDay(d, 'US')) days++;
    d = addDays(d, 1);
  }
  if (!days) return null;
  const growth = 1 + 0.004 * monthsSince(pk);
  const byDept: Record<string, number> = {};
  for (const [dep, n] of Object.entries(PEOPLE_DEPTS_US)) byDept[dep] = Math.round(((n * SALARY_US * 12) / 260) * days * growth * 1.162 / 100) * 100;
  return { amount: Object.values(byDept).reduce((s, x) => s + x, 0), byDept, days, from: addDays(covered, 1) };
}

// ---------------------------------------------------------------------------- cards
export function cardActivity(st: HistoryState, entity: 'BWL-US' | 'BWL-UK', pk: string, opts: { uncodedFrom?: string; count?: number } = {}) {
  const { b } = st;
  const merchants = MERCHANTS.filter((m) => m.entity === entity);
  const cards = st.cardIds.filter((c) => c.entity === entity);
  const totalWeight = merchants.reduce((s, m) => s + m.weight, 0);
  const n = opts.count ?? (entity === 'BWL-US' ? b.rng.int(62, 78) : b.rng.int(16, 22));
  const end = periodEnd(pk);
  for (let i = 0; i < n; i++) {
    let r = b.rng.next() * totalWeight;
    let m = merchants[0]!;
    for (const x of merchants) {
      r -= x.weight;
      if (r <= 0) {
        m = x;
        break;
      }
    }
    const card = b.rng.pick(cards);
    const date = addDays(periodStart(pk), b.rng.int(0, Number(end.slice(8)) - 1));
    if (date > SCENARIO.lastActivityDate) continue;
    const amount = Math.round(b.rng.float(m.min, m.max));
    const uncoded = !!opts.uncodedFrom && date >= opts.uncodedFrom;
    addCardTxn(st, { entity, card, date, merchant: m.name, mcc: m.mcc, amount, account: m.account, dept: card.dept, uncoded });
  }
}

export function addCardTxn(st: HistoryState, t: { entity: string; card: HistoryState['cardIds'][number]; date: string; merchant: string; mcc: string | null; amount: number; account: string; dept: string; uncoded?: boolean; memo?: string | null; receipt?: 'attached' | 'missing' | 'not_required' }) {
  const { b } = st;
  const ext = `${t.entity === 'BWL-US' ? 'KCU' : 'KCK'}-${t.date.replace(/-/g, '')}-${b.rng.int(100000, 999999)}`;
  let jeId: string | null = null;
  if (!t.uncoded) {
    jeId = b.je({ entity: t.entity, date: t.date, type: 'standard', memo: `Card ••${t.card.last4} ${t.merchant}`, source: 'subledger', sourceRef: ext, ...sys(st), lines: [{ account: t.account, debit: t.amount, department: requiresDept(t.account) ? t.dept : null, memo: t.merchant }, { account: '2200', credit: t.amount, memo: `${t.card.name} ••${t.card.last4}` }] });
    st.cardBalance[t.entity] = (st.cardBalance[t.entity] ?? 0) + t.amount;
  }
  b.add('card_transactions', {
    entity_id: b.ent(t.entity), card_id: t.card.id, txn_date: t.date, post_date: addDays(t.date, 1) > SCENARIO.lastActivityDate ? t.date : addDays(t.date, 1), merchant_name: t.merchant, mcc: t.mcc, amount_minor: t.amount,
    currency: t.entity === 'BWL-US' ? 'USD' : 'GBP', memo: t.memo ?? null, receipt_status: t.receipt ?? (t.amount > 7_500 ? 'attached' : b.rng.chance(0.9) ? 'attached' : 'missing'),
    account_id: t.uncoded ? null : b.acct(t.account), department: t.uncoded ? null : requiresDept(t.account) ? t.dept : null, location: null, product_class: null, project: null,
    coding_source: t.uncoded ? null : 'human', coding_confidence: null, status: t.uncoded ? 'pending_coding' : 'posted', journal_entry_id: jeId, import_batch_id: null, source_document_id: null, source_line: null, external_id: ext,
  });
}

export function settleCards(st: HistoryState, entity: 'BWL-US' | 'BWL-UK', date: string) {
  const bal = st.cardBalance[entity] ?? 0;
  if (bal <= 0) return;
  const ba = st.bankAccount[entity]!;
  st.b.je({ entity, date, type: 'standard', memo: 'Corporate card statement payment', source: 'subledger', sourceRef: `CARD-${date}`, ...sys(st), lines: [{ account: '2200', debit: bal }, { account: ba.gl, credit: bal }] });
  bank(st, entity, date, -bal, 'KEYSTONE CARD PAYMENT', 'Keystone Card Services', `CARD-${date}`, '455');
  st.cardBalance[entity] = 0;
}

// ---------------------------------------------------------------------------- revenue
export function monthRevenue(st: HistoryState, pk: string, entity: 'BWL-US' | 'BWL-UK') {
  const { b } = st;
  const cal = entity === 'BWL-US' ? 'US' : 'UK';
  const first = businessDayOnOrAfter(periodStart(pk), cal);
  const month = Number(pk.slice(5));
  for (const c of st.customers.filter((x) => x.entity === entity && x.startKey <= pk)) {
    if (c.billing === 'monthly') {
      issueInvoice(st, c, first, [{ description: `Platform subscription – ${pk}`, amount: Math.round(c.arr / 12), revenueType: 'subscription', account: '4000', start: periodStart(pk), end: periodEnd(pk), productClass: 'PLATFORM' }]);
    } else if (c.anniversary === month || c.startKey === pk) {
      issueInvoice(st, c, first, [{ description: `Annual platform subscription ${pk} to ${shiftPeriod(pk, 11)}`, amount: c.arr, revenueType: 'subscription', account: '2300', start: periodStart(pk), end: periodEnd(shiftPeriod(pk, 11)), productClass: 'PLATFORM' }]);
    }
  }
  // hardware and services
  // only the US entity carries sensor inventory; the UK sells subscriptions and services
  const hwCount = entity === 'BWL-US' ? b.rng.int(3, 6) : 0;
  const custs = st.customers.filter((x) => x.entity === entity);
  for (let i = 0; i < hwCount; i++) {
    const c = b.rng.pick(custs);
    const date = businessDayOnOrBefore(addDays(periodStart(pk), b.rng.int(2, 26)), cal);
    if (date > SCENARIO.lastActivityDate) continue;
    const kits = b.rng.int(8, 60);
    const amount = kits * (entity === 'BWL-US' ? 1_450_00 : 1_120_00);
    issueInvoice(st, c, date, [{ description: `${kits} Gen-2 sensor kits`, amount, revenueType: 'hardware', account: '4100', productClass: 'HARDWARE' }]);
    b.je({ entity, date, type: 'standard', memo: `COGS – ${kits} sensor kits to ${c.name}`, source: 'subledger', sourceRef: `COGS-${date}-${i}`, ...sys(st), lines: [{ account: '5100', debit: Math.round(amount * 0.52), product_class: 'HARDWARE' }, { account: '1300', credit: Math.round(amount * 0.52) }] });
  }
  const svc = entity === 'BWL-US' ? b.rng.int(1, 3) : b.rng.int(0, 1);
  for (let i = 0; i < svc; i++) {
    const c = b.rng.pick(custs);
    const date = businessDayOnOrBefore(addDays(periodStart(pk), b.rng.int(5, 27)), cal);
    if (date > SCENARIO.lastActivityDate) continue;
    issueInvoice(st, c, date, [{ description: 'Installation and calibration services', amount: Math.round(b.rng.float(8_000_00, 46_000_00) / 100) * 100, revenueType: 'services', account: '4200', productClass: 'SERVICES' }]);
  }
}

/** Ratable release of annual subscriptions billed into deferred revenue (ASC 606 over-time). */
export function releaseDeferredRevenue(st: HistoryState, pk: string, entity: 'BWL-US' | 'BWL-UK') {
  let total = 0;
  for (const c of st.customers.filter((x) => x.entity === entity && x.billing === 'annual' && x.startKey <= pk)) total += Math.round(c.arr / 12);
  if (!total) return;
  st.b.je({ entity, date: periodEnd(pk), type: 'recurring', memo: `Deferred revenue release – ${pk}`, source: 'system', sourceRef: `DEFREV-${pk}`, ...sys(st), lines: [{ account: '2300', debit: total }, { account: '4000', credit: total, product_class: 'PLATFORM' }] });
}

