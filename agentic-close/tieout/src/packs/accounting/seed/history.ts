// ---------------------------------------------------------------------------- intercompany & FX
export function intercompanyCharge(st: HistoryState, date: string, gbp: number, opts: { ukOnlyExtra?: { gbp: number; memo: string } } = {}) {
  const { b } = st;
  const rate = spotOn(st, date);
  const usd = convert(gbp, rate);
  const us = b.ent('BWL-US');
  const uk = b.ent('BWL-UK');
  const pk = periodKeyOf(date);
  b.je({ entity: 'BWL-UK', date, type: 'standard', memo: `R&D services to BWL-US – ${pk}`, source: 'system', sourceRef: `IC-UK-${pk}-01`, ...sys(st), counterpartyEntityId: us, lines: [{ account: '1400', debit: gbp, counterparty_entity_id: us }, { account: '4900', credit: gbp, counterparty_entity_id: us }] });
  st.icReceivableGbp += gbp;
  b.je({ entity: 'BWL-US', date, type: 'standard', memo: `R&D services from BWL-UK – ${pk}`, source: 'system', sourceRef: `IC-UK-${pk}-01`, ...sys(st), counterpartyEntityId: uk, lines: [{ account: '6950', debit: usd, department: 'RND', counterparty_entity_id: uk, txn_currency: 'GBP', txn_amount_minor: gbp, fx_rate: rate }, { account: '2400', credit: usd, counterparty_entity_id: uk, txn_currency: 'GBP', txn_amount_minor: -gbp, fx_rate: rate }] });
  st.icPayableGbp += gbp;
  st.icPayableUsd += usd;
  if (opts.ukOnlyExtra) {
    b.je({ entity: 'BWL-UK', date, type: 'standard', memo: opts.ukOnlyExtra.memo, source: 'system', sourceRef: `IC-UK-${pk}-02`, ...sys(st), counterpartyEntityId: us, lines: [{ account: '1400', debit: opts.ukOnlyExtra.gbp, counterparty_entity_id: us }, { account: '4900', credit: opts.ukOnlyExtra.gbp, counterparty_entity_id: us }] });
    st.icReceivableGbp += opts.ukOnlyExtra.gbp;
  }
}

export function fxRevaluation(st: HistoryState, pk: string): { adjustment: number; target: number } {
  const rate = st.closing.get(pk)!;
  const target = convert(st.icPayableGbp, rate);
  const adj = target - st.icPayableUsd; // + means liability grew -> loss
  if (adj !== 0) {
    st.b.je({
      entity: 'BWL-US', date: periodEnd(pk), type: 'fx_revaluation', memo: `Remeasure GBP intercompany payable at ${rate.toFixed(4)} – ${pk}`, source: 'manual', sourceRef: `FXREV-${pk}`, ...manual(st, 'jordan', 'casey'),
      lines: adj > 0 ? [{ account: '7110', debit: adj }, { account: '2400', credit: adj, counterparty_entity_id: st.b.ent('BWL-UK') }] : [{ account: '2400', debit: -adj, counterparty_entity_id: st.b.ent('BWL-UK') }, { account: '7110', credit: -adj }],
    });
    st.icPayableUsd = target;
  }
  return { adjustment: adj, target };
}

export function settleIntercompany(st: HistoryState, date: string) {
  const { b } = st;
  const gbp = st.icPayableGbp;
  if (gbp <= 0) return;
  const rate = spotOn(st, date);
  const usd = convert(gbp, rate);
  const carrying = st.icPayableUsd;
  const realized = carrying - usd; // positive = gain (paid less than carried)
  const uk = b.ent('BWL-UK');
  b.je({ entity: 'BWL-US', date, type: 'standard', memo: `Intercompany settlement to BWL-UK (£${(gbp / 100).toLocaleString('en-US')})`, source: 'subledger', sourceRef: `ICSET-${date}`, ...sys(st), lines: [{ account: '2400', debit: carrying, counterparty_entity_id: uk, txn_currency: 'GBP', txn_amount_minor: gbp, fx_rate: rate }, { account: '1010', credit: usd }, ...(realized > 0 ? [{ account: '7100', credit: realized }] : realized < 0 ? [{ account: '7100', debit: -realized }] : [])] });
  bank(st, 'BWL-US', date, -usd, 'WIRE OUT BRAMBLEWOOD LABS LTD GBP SETTLEMENT', 'Bramblewood Labs Ltd', `ICSET-${date}`, '495');
  const us = b.ent('BWL-US');
  b.je({ entity: 'BWL-UK', date, type: 'standard', memo: 'Intercompany settlement from BWL-US', source: 'subledger', sourceRef: `ICSET-${date}`, ...sys(st), lines: [{ account: '1030', debit: gbp }, { account: '1400', credit: gbp, counterparty_entity_id: us }] });
  bank(st, 'BWL-UK', date, gbp, 'CHAPS IN BRAMBLEWOOD LABS INC', 'Bramblewood Labs, Inc.', `ICSET-${date}`, 'CHAPS');
  st.icPayableGbp = 0;
  st.icPayableUsd = 0;
  st.icReceivableGbp -= gbp;
}

/** Eliminations in the BWL-ELIM ledger (USD): month P&L (permanent) + balances (auto-reversing). */
export function eliminations(st: HistoryState, pk: string, ukIcRevenueGbp: number, usIcExpenseUsd: number) {
  const { b } = st;
  const avg = st.average.get(pk)!;
  const closing = st.closing.get(pk)!;
  const rev = convert(ukIcRevenueGbp, avg);
  const diff = rev - usIcExpenseUsd;
  b.je({ entity: 'BWL-ELIM', date: periodEnd(pk), type: 'elimination', memo: `Eliminate intercompany R&D services – ${pk}`, source: 'manual', sourceRef: `ELIM-PL-${pk}`, ...manual(st, 'jordan', 'casey'), lines: [{ account: '4900', debit: rev }, { account: '6950', credit: usIcExpenseUsd, department: 'RND' }, ...(diff > 0 ? [{ account: '7120', credit: diff }] : diff < 0 ? [{ account: '7120', debit: -diff }] : [])] });
  const recUsd = convert(st.icReceivableGbp, closing);
  const payUsd = st.icPayableUsd;
  if (recUsd === 0 && payUsd === 0) return;
  const d2 = recUsd - payUsd;
  jeAutoReversing(st, { entity: 'BWL-ELIM', date: periodEnd(pk), type: 'elimination', memo: `Eliminate intercompany balances at ${pk} (reverses next month)`, source: 'manual', sourceRef: `ELIM-BS-${pk}`, ...manual(st, 'jordan', 'casey'), autoReverseOn: periodStart(shiftPeriod(pk, 1)), lines: [{ account: '2400', debit: payUsd }, { account: '1400', credit: recUsd }, ...(d2 > 0 ? [{ account: '7120', debit: d2 }] : d2 < 0 ? [{ account: '7120', credit: -d2 }] : [])] });
  return { recUsd, payUsd };
}

export function jeAutoReversing(st: HistoryState, spec: JeSpec): string {
  const id = st.b.je(spec);
  if (spec.autoReverseOn) st.reversals.push({ date: spec.autoReverseOn, jeId: id, spec });
  return id;
}

/** Post scheduled auto-reversals due on or before `upTo` (AX-ACR-01). */
export function postDueReversals(st: HistoryState, upTo: string) {
  const due = st.reversals.filter((r) => r.date <= upTo);
  for (const r of due) {
    st.b.je({
      ...r.spec,
      date: r.date,
      type: 'reversing',
      memo: `Reversal of ${st.b.jeNumbers.get(r.jeId)}: scheduled auto-reversal`,
      source: 'system',
      preparedBy: 'system:auto-reversal',
      approvedBy: 'system:auto-reversal',
      route: 'system',
      autoReverseOn: null,
      reversesJeId: r.jeId,
      lines: r.spec.lines.map((l) => ({ ...l, debit: l.credit, credit: l.debit, txn_amount_minor: l.txn_amount_minor === null || l.txn_amount_minor === undefined ? l.txn_amount_minor : -l.txn_amount_minor })),
    });
  }
  st.reversals = st.reversals.filter((r) => r.date > upTo);
}

