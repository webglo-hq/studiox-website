/**
 * `npm run docs:erd`: Mermaid entity-relationship diagrams generated from the schema metadata
 * (which is itself generated from migrations/*.sql), so the ERD can never drift from the DDL.
 * Writes docs/erd.md: four focused diagrams with every column, plus the full relationship map.
 */
