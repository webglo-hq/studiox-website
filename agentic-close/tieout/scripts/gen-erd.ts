const known = new Set(GROUPS.flatMap((g) => g.tables));
const missing = Object.keys(META).filter((t) => t !== 'schema_migrations' && t !== 'counters' && !known.has(t));
if (missing.length) throw new Error(`ERD groups miss tables: ${missing.join(', ')}`);

function entity(t: TableMeta): string {
  const uniqueCols = new Set(t.uniques.filter((u) => u.length === 1).map((u) => u[0]!));
  const rows = t.columns.map((c) => {
    const keys = [c.primaryKey || c.name === 'id' ? 'PK' : null, c.references ? 'FK' : null, c.unique || uniqueCols.has(c.name) ? 'UK' : null].filter(Boolean).join(', ');
    return `    ${c.type.replace(/[^a-z0-9_]/gi, '_')} ${c.name}${keys ? ` ${keys}` : ''}${c.nullable ? ' "nullable"' : ''}`;
  });
  return `  ${t.name} {\n${rows.join('\n')}\n  }`;
}

function relations(tables: string[], within: Set<string> | null): string[] {
  const out: string[] = [];
  for (const name of tables) {
    for (const c of META[name]!.columns) {
      const ref = c.references?.table;
      if (!ref || c.name === 'tenant_id' || (within && !within.has(ref))) continue;
      out.push(`  ${ref} ${c.nullable ? '|o' : '||'}--o{ ${name} : "${c.name}"`);
    }
  }
  return out;
}

const parts: string[] = [
  '# Data model (generated)',
  '',
  'Generated by `npm run docs:erd` from the schema metadata, which `npm run gen` derives from `migrations/*.sql`. ' +
    `${Object.keys(META).length} tables. Money is stored in integer minor units; JSON columns are typed in \`src/schema/json-types.ts\`. ` +
    'Foreign keys to `tenants` are omitted from the diagrams for readability: every tenant-scoped table has one.',
  '',
];
for (const g of GROUPS) {
  const set = new Set(g.tables);
  parts.push(`## ${g.title}`, '', g.note, '', '```mermaid', 'erDiagram', ...relations(g.tables, set), ...g.tables.map((t) => entity(META[t]!)), '```', '');
}
const all = Object.keys(META).filter((t) => t !== 'schema_migrations');
parts.push('## All relationships', '', 'Every foreign key across the four areas (columns omitted).', '', '```mermaid', 'erDiagram', ...relations(all, null), '```', '');
writeFileSync(resolve('docs/erd.md'), parts.join('\n'));
console.log(`docs/erd.md: ${Object.keys(META).length} tables, ${relations(all, null).length} relationships`);
